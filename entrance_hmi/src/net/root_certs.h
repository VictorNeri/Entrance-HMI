//
// Two roots per host, each verified alone against the live chain
// (2026-11-14): the host's own root plus the older root that
// cross-signs it, so the pin keeps working whichever of the two paths
// the server's chain resolves to. A root moving entirely to a
// different CA would make that API's fetches fail with a TLS error —
// visible as the STATUS screen error line, a "[http] ... TLS" net-log
// line, and the stale-data badges — until these are updated.
//
